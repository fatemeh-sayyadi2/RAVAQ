export function resolveVerifiedCategoryAsset(
  illustrationKey: string,
  role: 'primary' | 'detail' | 'packaging' | 'lifestyle' = 'primary'
): string {
  const baseKey = illustrationKey.replace(/-(detail|packaging|lifestyle)$/, '');
  const detectedRole = illustrationKey.endsWith('-detail')
    ? 'detail'
    : illustrationKey.endsWith('-packaging')
    ? 'packaging'
    : illustrationKey.endsWith('-lifestyle')
    ? 'lifestyle'
    : role;

  const entry = VERIFIED_PRODUCT_JPG_MAP[baseKey];
  if (entry) {
    return entry[detectedRole] || entry.primary;
  }

  if (baseKey === 'gift-nowruz' || baseKey === 'gift-yalda' || baseKey === 'gift-visiting' || baseKey === 'occasion') {
    return '/assets/products/nowruz-gift-box.jpg';
  }
  if (baseKey.startsWith('gift') || baseKey === 'giftbox') {
    return '/assets/products/gift-box-signature.jpg';
  }
  if (
    baseKey.includes('saffron') ||
    baseKey.includes('herbal') ||
    baseKey.includes('pantry') ||
    baseKey.includes('hospitality-pack')
  ) {
    return '/assets/products/saffron-jar-ravaq.jpg';
  }
  if (
    baseKey === 'crafts' ||
    baseKey === 'pottery' ||
    baseKey === 'ceramic-bowl' ||
    baseKey === 'runner' ||
    baseKey === 'arch-decor' ||
    baseKey === 'craft-set'
  ) {
    return '/assets/products/handicrafts-trio.jpg';
  }
  if (
    baseKey === 'sweets' ||
    baseKey === 'gaz' ||
    baseKey === 'sohan' ||
    baseKey === 'baklava' ||
    baseKey === 'nan-berenji' ||
    baseKey === 'nokhodchi' ||
    baseKey === 'qottab' ||
    baseKey === 'kolompeh' ||
    baseKey === 'koloocheh' ||
    baseKey === 'baslogh' ||
    baseKey === 'poolaki' ||
    baseKey === 'masghati' ||
    baseKey === 'sweet-assortment'
  ) {
    return '/assets/products/sweets-platter.jpg';
  }
  return '/assets/products/pistachios-bowl.jpg';
}

function makeImages(slug: string, name: string, illustrationKey: string): ProductImage[] {
  return [
    {
      id: `${slug}-img-primary`,
      url: resolveVerifiedCategoryAsset(illustrationKey, 'primary'),
      role: 'primary',
      alt: `تصویر اصلی محصول ${name} در فروشگاه رواق`,
      illustrationKey,
    },
    {
      id: `${slug}-img-detail`,
      url: resolveVerifiedCategoryAsset(illustrationKey, 'detail'),
      role: 'detail',
      alt: `نمای نزدیک بافت و جزئیات ${name}`,
      illustrationKey: `${illustrationKey}-detail`,
    },
    {
      id: `${slug}-img-packaging`,
      url: resolveVerifiedCategoryAsset(illustrationKey, 'packaging'),
      role: 'packaging',
      alt: `بسته‌بندی اختصاصی رواق برای ${name}`,
      illustrationKey: `${illustrationKey}-packaging`,
    },
    {
      id: `${slug}-img-lifestyle`,
      url: resolveVerifiedCategoryAsset(illustrationKey, 'lifestyle'),
      role: 'lifestyle',
      alt: `چیدمان پذیرایی ${name} در فضای ایرانی`,
      illustrationKey: `${illustrationKey}-lifestyle`,
    },
  ];
}

